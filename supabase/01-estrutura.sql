-- ----------------------------------------------------------------------------
-- Funcao que mantem o campo atualizado_em sempre correto
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.marcar_atualizacao()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.atualizado_em = now();
  RETURN NEW;
END;
$$;

