-- ============================================================================
-- Gatilhos de atualizado_em + seguranca (RLS)
--
-- O sistema conecta no banco pela string de conexao do Postgres, com o usuario
-- dono das tabelas - esse caminho nao passa por RLS.
--
-- Ligamos RLS mesmo assim e NAO criamos nenhuma policy: isso bloqueia as chaves
-- publicas do Supabase (anon / authenticated). Sem isso, qualquer pessoa com a
-- chave anon do projeto conseguiria ler contratos, faturas e atas pela API
-- REST automatica do Supabase.
-- ============================================================================
DO $$
DECLARE
  nome_tabela text;
  papel       text;
  -- No Supabase os papeis anon/authenticated existem; fora dele (um Postgres
  -- comum, ou um ambiente de teste) nao existem. Por isso a revogacao e
  -- condicional, senao o arquivo inteiro falharia.
  papeis_publicos text[] := ARRAY['anon', 'authenticated'];
BEGIN
  FOR nome_tabela IN
    SELECT c.relname
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'r'
  LOOP
    -- gatilho de atualizado_em
    EXECUTE format('DROP TRIGGER IF EXISTS trg_atualizado_em ON public.%I', nome_tabela);
    EXECUTE format(
      'CREATE TRIGGER trg_atualizado_em BEFORE UPDATE ON public.%I
         FOR EACH ROW EXECUTE FUNCTION public.marcar_atualizacao()',
      nome_tabela
    );

    -- trava a API publica do Supabase
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', nome_tabela);

    FOREACH papel IN ARRAY papeis_publicos LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = papel) THEN
        EXECUTE format('REVOKE ALL ON public.%I FROM %I', nome_tabela, papel);
      END IF;
    END LOOP;
  END LOOP;
END;
$$;

-- Confirmacao
SELECT 'Estrutura criada: ' || count(*) || ' tabelas.' AS resultado
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = 'public' AND c.relkind = 'r';
